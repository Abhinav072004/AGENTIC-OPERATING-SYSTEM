#!/usr/bin/env python3
"""Generate validated compile-time configuration; preserve mtime if unchanged."""
import argparse
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--output", type=Path, required=True)
parser.add_argument("--log-level", choices=("DEBUG", "INFO", "WARNING", "ERROR", "PANIC"), required=True)
parser.add_argument("--selftest", choices=("none", "logs", "panic", "assert"), required=True)
args = parser.parse_args()
content = f'''/* Generated by tools/configure.py. Do not edit. */
#ifndef AGENTICOS_CONFIG_H
#define AGENTICOS_CONFIG_H
#define AGENTICOS_VERSION "0.2.0"
#define CONFIG_LOG_LEVEL LOG_{args.log_level}
#define CONFIG_SELFTEST {("none", "logs", "panic", "assert").index(args.selftest)}
#endif
'''
args.output.parent.mkdir(parents=True, exist_ok=True)
if not args.output.exists() or args.output.read_text() != content:
    temporary = args.output.with_suffix(".tmp")
    temporary.write_text(content)
    temporary.replace(args.output)
